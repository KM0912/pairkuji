import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export function renderServiceWorker(buildId, precache) {
  return `/* generated by scripts/write-sw.mjs — build ${buildId} */
const BUILD_ID = ${JSON.stringify(buildId)};
const CACHE = 'pairkuji-' + BUILD_ID;
const PRECACHE = ${JSON.stringify(precache)};
const NAV_TIMEOUT_MS = 4000;
const STATIC_TIMEOUT_MS = 8000;

function withTimeout(work, ms) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('timeout')), ms);
    work.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      }
    );
  });
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        PRECACHE.map(async (url) => {
          try {
            const response = await withTimeout(fetch(url), STATIC_TIMEOUT_MS);
            if (response && response.ok) await cache.put(url, response);
          } catch {
            // 1件失敗しても他の画面はキャッシュする
          }
        })
      );
      await self.skipWaiting();
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))
      );
      await self.clients.claim();
    })()
  );
});

function isRscRequest(request, url) {
  if (request.headers.get('RSC') === '1') return true;
  if (request.headers.get('Next-Router-Prefetch') === '1') return true;
  return url.searchParams.has('_rsc');
}

async function revalidateRsc(request) {
  try {
    const response = await withTimeout(fetch(request), NAV_TIMEOUT_MS);
    if (response && response.ok) {
      const cache = await caches.open(CACHE);
      await cache.put(request, response.clone());
    }
  } catch {
    // 古いRSCを残す
  }
}

async function handleRsc(event, request) {
  const cached = await caches.match(request);
  if (cached) {
    event.waitUntil(revalidateRsc(request));
    return cached;
  }
  try {
    const response = await withTimeout(fetch(request), NAV_TIMEOUT_MS);
    if (response && response.ok) {
      const cache = await caches.open(CACHE);
      await cache.put(request, response.clone());
      return response;
    }
    if (response) return response;
  } catch {
    // タイムアウト時は待たずに失敗させる
  }
  return new Response('', { status: 504 });
}

function historyDetailId(pathname) {
  const match = pathname.match(/^\\/history\\/([^/]+)\\/?$/);
  return match ? decodeURIComponent(match[1]) : null;
}

function navigationCacheKey(url) {
  if (url.pathname === '/history') return new URL('/history', url.origin).href;
  return url.origin + url.pathname;
}

async function handleNavigate(request, url) {
  const detailId = historyDetailId(url.pathname);
  if (detailId) {
    try {
      const response = await withTimeout(fetch(request), NAV_TIMEOUT_MS);
      if (response && response.ok) return response;
    } catch {
      // オフラインでは一覧ページへ寄せる
    }
    const cachedHistory =
      (await caches.match(new URL('/history', url.origin).href)) ||
      (await caches.match('/history'));
    if (cachedHistory) {
      return Response.redirect(
        new URL('/history?id=' + encodeURIComponent(detailId), url.origin).href,
        302
      );
    }
    return new Response('オフラインではこの画面を開けません', {
      status: 503,
      headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    });
  }

  const cacheKey = navigationCacheKey(url);
  try {
    const response = await withTimeout(fetch(request), NAV_TIMEOUT_MS);
    if (response && response.ok) {
      const cache = await caches.open(CACHE);
      await cache.put(cacheKey, response.clone());
      return response;
    }
  } catch {
    // キャッシュへフォールバック
  }
  const cached =
    (await caches.match(cacheKey)) || (await caches.match(url.pathname));
  if (cached) return cached;
  return new Response('オフラインではこの画面を開けません', {
    status: 503,
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
}

async function handleStatic(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const response = await withTimeout(fetch(request), STATIC_TIMEOUT_MS);
    if (response && response.ok) {
      const cache = await caches.open(CACHE);
      await cache.put(request, response.clone());
      return response;
    }
    return response;
  } catch {
    return new Response('', { status: 504 });
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigate(request, url));
    return;
  }

  if (isRscRequest(request, url)) {
    event.respondWith(handleRsc(event, request));
    return;
  }

  if (url.pathname.startsWith('/_next/static/')) {
    event.respondWith(handleStatic(request));
  }
});
`;
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (!entry.name.endsWith('.map')) {
      files.push(full);
    }
  }
  return files;
}

const isMain =
  process.argv[1] != null &&
  import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  const root = process.cwd();
  const buildId = (await readFile(path.join(root, '.next', 'BUILD_ID'), 'utf8')).trim();
  const staticRoot = path.join(root, '.next', 'static');
  const staticFiles = await walk(staticRoot);
  const staticUrls = staticFiles.map((file) => {
    const relative = path.relative(staticRoot, file).split(path.sep).join('/');
    return `/_next/static/${relative}`;
  });
  const precache = [
    '/',
    '/practice',
    '/members',
    '/stats',
    '/history',
    '/manifest.json',
    '/icon-192.png',
    '/icon-512.png',
    '/favicon-32x32.png',
    ...staticUrls,
  ];
  await writeFile(path.join(root, 'public', 'sw.js'), renderServiceWorker(buildId, precache));
  console.log(`wrote public/sw.js (${precache.length} urls, ${buildId})`);
}
